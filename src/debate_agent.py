# ---------------------------
# Debate Orchestrator
# ---------------------------
def run_debate(agent_a, agent_b, topic, context_pages, rounds=2):
    transcript = []

    a_stmt = agent_a.propose(topic, context_pages)
    transcript.append((agent_a.role_name, a_stmt))

    b_stmt = agent_b.propose(topic, context_pages)
    transcript.append((agent_b.role_name, b_stmt))

    last_a, last_b = a_stmt, b_stmt
    for _ in range(rounds):
        b_reply = agent_b.rebut(last_a, context_pages)
        transcript.append((agent_b.role_name, b_reply))
        last_b = b_reply

        a_reply = agent_a.rebut(last_b, context_pages)
        transcript.append((agent_a.role_name, a_reply))
        last_a = a_reply

    a_conc = agent_a.conclude(transcript)
    b_conc = agent_b.conclude(transcript)
    transcript.append((f"{agent_a.role_name} - Conclusion", a_conc))
    transcript.append((f"{agent_b.role_name} - Conclusion", b_conc))

    consensus_points = _derive_consensus(a_conc, b_conc)

    return {
        "transcript": transcript,
        "conclusion_a": a_conc,
        "conclusion_b": b_conc,
        "consensus": consensus_points,
    }

def _derive_consensus(text_a, text_b):
    tokens_a = set(re.findall(r"\b\w{4,}\b", text_a.lower()))
    tokens_b = set(re.findall(r"\b\w{4,}\b", text_b.lower()))
    overlap = sorted(tokens_a & tokens_b)
    return overlap[:6]

def run_debate_and_save(agent_a, agent_b, context_pages, topic, output_path):
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    result = run_debate(agent_a, agent_b, topic, context_pages)

    with open(output_path, "w", encoding="utf-8") as fh:
        fh.write(f"Policy Debate Brief - Topic: {topic}\n\n")
        fh.write("--- TRANSCRIPT ---\n")
        for role, stmt in result["transcript"]:
            fh.write(f"{role}:\n{stmt}\n\n")
        fh.write("--- CONSENSUS ---\n")
        for p in result["consensus"]:
            fh.write(f"- {p}\n")
        fh.write("\n--- CONCLUSIONS ---\n")
        fh.write(f"{agent_a.role_name}:\n{result['conclusion_a']}\n\n")
        fh.write(f"{agent_b.role_name}:\n{result['conclusion_b']}\n")

    logger.info("Debate saved to %s", output_path)

    # Print output on console
    print(f"Debate saved to {output_path}")
    print("\n--- TRANSCRIPT ---")
    for role, stmt in result["transcript"]:
        print(f"{role}:\n{stmt}\n")
    print("--- CONSENSUS ---")
    for p in result["consensus"]:
        print(f"- {p}")
    print("\n--- CONCLUSIONS ---")
    print(f"{agent_a.role_name}:\n{result['conclusion_a']}\n")
    print(f"{agent_b.role_name}:\n{result['conclusion_b']}\n")

    return result

