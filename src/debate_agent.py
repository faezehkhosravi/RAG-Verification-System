# Base class for debate agents
# ---------------------------
class DebateAgentBase:
    def __init__(self, role_name: str, llm_fn: Callable[[str], str] = None):
        self.role_name = role_name
        self.llm_fn = llm_fn or (lambda prompt: "LLM simulated response.")

    def propose(self, topic: str, context_pages: List[Tuple[str,int,str]]) -> str:
        raise NotImplementedError

    def rebut(self, other_statement: str, context_pages: List[Tuple[str,int,str]]) -> str:
        raise NotImplementedError

    def conclude(self, transcript: List[Tuple[str,str]]) -> str:
        raise NotImplementedError

# ---------------------------
# Pro-Innovation Agent
# ---------------------------
class DebateAgentA(DebateAgentBase):
    def __init__(self, llm_fn=None):
        super().__init__("Pro-Innovation Agent", llm_fn)

    def propose(self, topic, context_pages):
        context = "\n".join([f"[src: {src}, p.{p}] {t}" for src,p,t in context_pages])
        prompt = f"Argue for innovation-friendly regulation on: {topic}\nContext:\n{context}\nProvide 4 short bullet points with citations."
        return self.llm_fn(prompt)

    def rebut(self, other_statement, context_pages):
        context = "\n".join([f"[src: {src}, p.{p}] {t}" for src,p,t in context_pages])
        prompt = f"Rebut opposing points:\n{other_statement}\nContext:\n{context}"
        return self.llm_fn(prompt)

    def conclude(self, transcript):
        ttext = "\n".join([f"{role}: {stmt}" for role,stmt in transcript])
        prompt = f"Based on debate transcript, list 3 agreed principles and 2 disagreements.\nTranscript:\n{ttext}"
        return self.llm_fn(prompt)

