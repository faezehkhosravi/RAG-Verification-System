class VerifierAgent:
    def __init__(
        self,
        nli_fn: Optional[Callable[[str,str],Dict[str,Any]]] = None,
        embed_fn: Optional[Callable[[List[str]], List[List[float]]]] = None,
        sim_threshold: float = 0.8
    ):
        self.nli_fn = nli_fn
        self.embed_fn = embed_fn
        self.sim_threshold = sim_threshold

    def _nli_check(self, premise: str, hypothesis: str) -> Dict[str,Any]:
        if self.nli_fn:
            try:
                res = self.nli_fn(premise, hypothesis)
                return {"label": res.get("label","NEUTRAL").upper(), "score": float(res.get("score",0.0))}
            except Exception as e:
                logger.exception("nli_fn failed: %s", e)
        # fallback heuristic
        hyp = hypothesis.lower()
        neg_words = ["not","no","never","n't","without"]
        neg = any(w in hyp for w in neg_words)
        overlap = len(set(re.findall(r"\b[a-zA-Z]{3,}\b", premise.lower())).intersection(
                      set(re.findall(r"\b[a-zA-Z]{3,}\b", hyp))
                  ))
        if neg and overlap>3: return {"label":"CONTRADICTION","score":0.6}
        if overlap>=5: return {"label":"ENTAILMENT","score":min(0.95,0.2+0.15*overlap)}
        return {"label":"NEUTRAL","score":0.5}

    def _embed_texts(self, texts: List[str]) -> List[List[float]]:
        if self.embed_fn:
            try:
                return self.embed_fn(texts)
            except Exception as e:
                logger.exception("embed_fn failed: %s", e)
        return [_simple_bow_embed(t) for t in texts]

    def _semantic_alignment(self, claim:str, evidence:str) -> float:
        emb_c, emb_e = self._embed_texts([claim, evidence])
        if not emb_c or not emb_e: return 0.0
        L = max(len(emb_c), len(emb_e))
        emb_c += [0.0]*(L-len(emb_c))
        emb_e += [0.0]*(L-len(emb_e))
        return _cosine(emb_c, emb_e)

    def _temporal_consistency(self, claim:str, evidence_texts:List[str], reference_date:Optional[str]=None) -> Dict[str,Any]:
        claim_dates = _extract_dates(claim)
        ev_dates = []
        for t in evidence_texts: ev_dates.extend(_extract_dates(t))
        ref_dt = None
        if reference_date:
            try: ref_dt = datetime.fromisoformat(reference_date)
            except: ref_dt = None
        consistent = True
        issues = []
        for cd in claim_dates:
            latest_ref = ref_dt
            if ev_dates: latest_ref = max(ev_dates) if not latest_ref else max(latest_ref,max(ev_dates))
            if latest_ref and cd>latest_ref:
                consistent=False
                issues.append(f"Claim date {cd.date()} is later than evidence/reference {latest_ref.date()}")
        return {"claim_dates":[d.isoformat() for d in claim_dates],
                "evidence_dates":[d.isoformat() for d in ev_dates],
                "reference_date": ref_dt.isoformat() if ref_dt else None,
                "consistent": consistent,
                "issues": issues}

    def verify_claims(self, claims:List[str], evidences:List[Tuple[str,int,str]], reference_date:Optional[str]=None) -> Dict[str,Any]:
        if not claims: raise ValueError("No claims provided")
        results = {"per_claim":[], "aggregated":{}}
        total, entail, contra, neutral, sim_ok, sim_total = 0,0,0,0,0,0
        evidence_texts = [t for _,_,t in evidences]
        concatenated = "\n\n".join(evidence_texts) if evidence_texts else ""
        for claim in claims:
            total+=1
            nli = self._nli_check(concatenated, claim)
            lbl = nli["label"]
            if lbl.startswith("ENT"): entail+=1
            if lbl.startswith("CON"): contra+=1
            if lbl.startswith("NEU"): neutral+=1
            best_sim=0.0
            best_idx=None
            for idx,(_,_,txt) in enumerate(evidences):
                sim = self._semantic_alignment(claim, txt)
                sim_total+=1
                if sim>=self.sim_threshold: sim_ok+=1
                if sim>best_sim:
                    best_sim=sim
                    best_idx=idx
            temporal = self._temporal_consistency(claim, evidence_texts, reference_date)
            results["per_claim"].append({
                "claim": claim,
                "nli": nli,
                "best_similarity": best_sim,
                "best_evidence_index": best_idx,
                "temporal": temporal
            })
        agg = {
            "total_claims":total,
            "entailment":entail,
            "contradiction":contra,
            "neutral":neutral,
            "similarity_threshold":self.sim_threshold,
            "sim_ok_count":sim_ok,
            "sim_total_checks":sim_total
        }
        results["aggregated"]=agg
        try: _save_metrics({"verifier":agg})
        except Exception as e: logger.exception("Failed to save metrics: %s", e)
        return results

