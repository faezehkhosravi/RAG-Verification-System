def _cosine(u: List[float], v: List[float]) -> float:
    if not u or not v:
        return 0.0
    dot = sum(a*b for a,b in zip(u,v))
    nu = math.sqrt(sum(a*a for a in u))
    nv = math.sqrt(sum(b*b for b in v))
    if nu==0 or nv==0: return 0.0
    return dot/(nu*nv)

def _simple_bow_embed(text: str, top_k: int=200) -> List[float]:
    tokens = re.findall(r"\b[a-zA-Z]{3,}\b", text.lower())
    if not tokens: return []
    counts = Counter(tokens)
    items = sorted(counts.items(), key=lambda x:(-x[1], x[0]))[:top_k]
    vec = [float(c) for _,c in items]
    norm = math.sqrt(sum(x*x for x in vec)) or 1.0
    return [x/norm for x in vec]

def _extract_dates(text: str) -> List[datetime]:
    dates = []
    for m in re.findall(r"\b(20\d{2}|19\d{2})-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])\b", text):
        try: dates.append(datetime.fromisoformat("-".join(m)))
        except: pass
    for m in re.findall(r"\b(January|February|March|April|May|June|July|August|September|October|November|December)\s+(20\d{2}|19\d{2})\b", text, re.IGNORECASE):
        try: dates.append(datetime.strptime(f"{m[0]} {m[1]}", "%B %Y"))
        except: pass
    return dates

