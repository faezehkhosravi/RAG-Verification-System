from pathlib import Path
import json
from typing import Any, Dict, List, Tuple, Optional

import numpy as np
from tqdm import tqdm
import matplotlib.pyplot as plt

# retrieval & embedding libraries
try:
    from rank_bm25 import BM25Okapi
except Exception:
    BM25Okapi = None

from sentence_transformers import SentenceTransformer, CrossEncoder
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

# ---- Configuration ----
PROJECT_ROOT = Path("/content/drive/MyDrive")
DOCS_JSON = PROJECT_ROOT / "results" / "classical_output.json"
QUERIES_JSON = PROJECT_ROOT / "queries" / "policy_queries.json"
OUT_JSON = PROJECT_ROOT / "results" / "retrieval_comparison.json"
PLOTS_DIR = PROJECT_ROOT / "results" / "plots"
PLOTS_DIR.mkdir(parents=True, exist_ok=True)

BI_ENCODER_NAME = "all-MiniLM-L6-v2"
CROSS_ENCODER_NAME = "cross-encoder/ms-marco-MiniLM-L-6-v2"

TOP_K_BM25 = 50
TOP_K_DENSE = 50
RERANK_TOP_K = 20
EVAL_K = 10

# ---- Helpers ----
def load_documents(path: Path) -> List[Dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(f"Missing documents file: {path}")
    with path.open("r", encoding="utf-8") as fh:
        docs = json.load(fh)
    normalized = []
    for d in docs:
        cid = d.get("chunk_id") or d.get("metadata", {}).get("chunk_id")
        text = d.get("original_text") or d.get("text") or ""
        normalized.append({"chunk_id": cid, "text": text})
    return normalized

def load_queries(path: Path) -> List[Dict[str, Any]]:
    # اگر فایل Queries وجود نداشته باشد یا نتواند لود شود
    if not path.exists():
        print(f"[warn] Queries file not found: {path}. Using sample query with mock relevant IDs.")
        # این mock IDs باید با chunk_id های واقعی در docs.json جایگزین شوند تا نتیجه واقعی بگیرید
        return [{"id": "q1", "query": "climate policy guidelines", "relevant": ["ac8b3538-en.pdf_12", "ac8b3538-en.pdf_1164"]}]

    with path.open("r", encoding="utf-8") as fh:
        payload = json.load(fh)
    queries: List[Dict[str, Any]] = []

    # اطمینان از وجود داده‌های مرتبط در صورت لود موفق
    if isinstance(payload, list):
        for i, item in enumerate(payload):
            if isinstance(item, str):
                # اگر فقط متن کوئری باشد، لیست مرتبط خالی فرض می‌شود
                queries.append({"id": f"q{i}", "query": item, "relevant": []})
            elif isinstance(item, dict):
                qid = item.get("id") or f"q{i}"
                query_text = item.get("query") or item.get("q") or item.get("question") or ""
                # اگر relevant خالی باشد، باید به صورت دستی تکمیل شود
                relevant = item.get("relevant") or item.get("relevant_ids") or []
                queries.append({"id": qid, "query": query_text, "relevant": relevant})

    # هشدار اگر هیچ کوئری با اسناد مرتبط نداشتیم
    if all(not q['relevant'] for q in queries) and queries:
        print("[CRITICAL WARNING] All loaded queries have an empty 'relevant' list. Plot will be empty.")

    return queries

def simple_tokenize(text: str) -> List[str]:
    return [t.lower() for t in text.split() if len(t) > 1]

# ---- Build indices ----
def build_bm25(docs: List[Dict[str, Any]]) -> Tuple[Optional[Any], List[List[str]]]:
    tokenized = [simple_tokenize(d["text"]) for d in docs]
    if BM25Okapi is not None:
        bm25 = BM25Okapi(tokenized)
        return bm25, tokenized
    return None, tokenized

def build_dense_index(docs: List[Dict[str, Any]], bi_encoder_name: str) -> Tuple[SentenceTransformer, np.ndarray]:
    model = SentenceTransformer(bi_encoder_name)
    texts = [d["text"] for d in docs]
    embeddings = model.encode(texts, show_progress_bar=True, convert_to_numpy=True)
    return model, embeddings

# ---- Retrieval ----
def bm25_retrieve(bm25: Optional[Any], tokenized_docs: List[List[str]], query: str, top_k: int) -> List[int]:
    if bm25 is not None:
        q_tok = simple_tokenize(query)
        scores = bm25.get_scores(q_tok)
        return np.argsort(scores)[::-1][:top_k].tolist()
    docs_texts = [" ".join(toks) for toks in tokenized_docs]
    if not docs_texts:
        return []
    vectorizer = TfidfVectorizer()
    doc_matrix = vectorizer.fit_transform(docs_texts)
    q_vec = vectorizer.transform([query])
    sims = cosine_similarity(q_vec, doc_matrix)[0]
    return np.argsort(sims)[::-1][:top_k].tolist()

def dense_retrieve(bi_model: SentenceTransformer, doc_embs: np.ndarray, query: str, top_k: int) -> List[int]:
    q_emb = bi_model.encode([query], convert_to_numpy=True)
    sims = cosine_similarity(q_emb, doc_embs)[0]
    return np.argsort(sims)[::-1][:top_k].tolist()

def cross_encoder_rerank(cross_encoder: CrossEncoder, query: str, candidates: List[Dict[str, Any]]) -> List[Tuple[str, float]]:
    pairs = [[query, c["text"]] for c in candidates]
    scores = cross_encoder.predict(pairs)
    chunk_ids = [c["chunk_id"] for c in candidates]
    return sorted(zip(chunk_ids, scores), key=lambda x: x[1], reverse=True)

def precision_at_k(retrieved: List[str], relevant: List[str], k: int) -> float:
    if k <= 0: return 0.0
    retrieved_k = retrieved[:k]
    if not relevant: return 0.0 # اگر لیست مرتبط خالی باشد، پرسیژن صفر است (که درست است)
    hits = sum(1 for r in retrieved_k if r in relevant)
    return hits / k

def recall_at_k(retrieved: List[str], relevant: List[str], k: int) -> float:
    if not relevant: return 0.0 # اگر لیست مرتبط خالی باشد، ریکال صفر است (که درست است)
    retrieved_k = set(retrieved[:k])
    hits = sum(1 for r in relevant if r in retrieved_k)
    return hits / max(1, len(relevant))

# ---- Main experiment ----
def run_experiment(top_k_bm25: int = TOP_K_BM25, top_k_dense: int = TOP_K_DENSE,
                   rerank_top_k: int = RERANK_TOP_K, eval_k: int = EVAL_K) -> None:
    print("Loading documents...")
    docs = load_documents(DOCS_JSON)
    print(f"{len(docs)} documents loaded.")

    print("Building BM25 index...")
    bm25, tokenized = build_bm25(docs)

    print(f"Building dense index with bi-encoder: {BI_ENCODER_NAME} ...")
    bi_model, doc_embs = build_dense_index(docs, BI_ENCODER_NAME)

    print(f"Loading cross-encoder model: {CROSS_ENCODER_NAME} ...")
    cross_encoder = CrossEncoder(CROSS_ENCODER_NAME)

    print("Loading queries...")
    queries = load_queries(QUERIES_JSON)
    print(f"{len(queries)} queries loaded.")

    results: Dict[str, Any] = {"n_docs": len(docs), "n_queries": len(queries), "per_query": []}
    baseline_precisions, reranked_precisions = [], []
    baseline_recalls, reranked_recalls = [], []

    for q in tqdm(queries, desc="Queries"):
        qid = q["id"]
        qtext = q["query"]
        relevant = [r for r in (q.get("relevant") or []) if r]

        # Baseline retrieval
        bm25_idx = bm25_retrieve(bm25, tokenized, qtext, top_k_bm25)
        dense_idx = dense_retrieve(bi_model, doc_embs, qtext, top_k_dense)
        union_idx = list(dict.fromkeys(bm25_idx + dense_idx))
        union_docs = [{"chunk_id": docs[i]["chunk_id"], "text": docs[i]["text"]} for i in union_idx]

        # Scores normalization using np.ptp
        q_emb = bi_model.encode([qtext], convert_to_numpy=True)
        union_embs = doc_embs[union_idx]
        dense_sims = cosine_similarity(q_emb, union_embs)[0] if len(union_embs) > 0 else np.zeros(len(union_docs))

        # محاسبه scores BM25 فقط برای چانک‌های موجود در union_docs
        # (قبلاً برای BM25 از شاخص‌ها استفاده می‌شد، اینجا باید scores را به دست آوریم)
        if bm25 is not None:
             bm25_scores_map = {docs[i]['chunk_id']: bm25.get_scores(simple_tokenize(qtext))[i] for i in union_idx}
             bm25_scores = np.array([bm25_scores_map.get(d['chunk_id'], 0.0) for d in union_docs])
        else:
             bm25_scores = np.zeros(len(union_docs))

        # Normalization
        bm25_norm = (bm25_scores - bm25_scores.min()) / (np.ptp(bm25_scores) + 1e-9) if len(bm25_scores) > 0 and np.ptp(bm25_scores) > 1e-9 else np.zeros(len(union_docs))
        dense_norm = (dense_sims - dense_sims.min()) / (np.ptp(dense_sims) + 1e-9) if len(dense_sims) > 0 and np.ptp(dense_sims) > 1e-9 else np.zeros(len(union_docs))

        # Combined Hybrid Score
        combined_scores = 0.6 * bm25_norm + 0.4 * dense_norm
        baseline_ranked = [union_docs[i]["chunk_id"] for i in np.argsort(combined_scores)[::-1]]

        # Reranking with cross-encoder
        rerank_candidates = union_docs[:rerank_top_k]
        if rerank_candidates:
            reranked = cross_encoder_rerank(cross_encoder, qtext, rerank_candidates)
            reranked_ranked = [cid for cid, score in reranked]
            remaining = [d["chunk_id"] for d in union_docs if d["chunk_id"] not in reranked_ranked]
            final_ranked = reranked_ranked + remaining
        else:
            final_ranked = baseline_ranked

        # Evaluation
        # اگر لیست relevant خالی باشد، p و r هر دو 0.0 خواهند بود.
        p_baseline = precision_at_k(baseline_ranked, relevant, eval_k)
        p_rerank = precision_at_k(final_ranked, relevant, eval_k)
        r_baseline = recall_at_k(baseline_ranked, relevant, eval_k)
        r_rerank = recall_at_k(final_ranked, relevant, eval_k)

        baseline_precisions.append(p_baseline)
        reranked_precisions.append(p_rerank)
        baseline_recalls.append(r_baseline)
        reranked_recalls.append(r_rerank)

        results["per_query"].append({
            "id": qid,
            "query": qtext,
            "n_candidates": len(union_idx),
            "baseline_ranked": baseline_ranked[:eval_k],
            "reranked_ranked": final_ranked[:eval_k],
            "relevant": relevant,
            "precision_baseline_at_k": p_baseline,
            "precision_rerank_at_k": p_rerank,
            "recall_baseline_at_k": r_baseline,
            "recall_rerank_at_k": r_rerank
        })

    # Aggregate
    def safe_mean(xs: List[float]) -> Optional[float]:
        arr = np.array([x for x in xs if x is not None])
        return float(np.nanmean(arr)) if arr.size else None

    summary = {
        "precision_baseline_at_k_mean": safe_mean(baseline_precisions),
        "precision_rerank_at_k_mean": safe_mean(reranked_precisions),
        "recall_baseline_at_k_mean": safe_mean(baseline_recalls),
        "recall_rerank_at_k_mean": safe_mean(reranked_recalls),
        "eval_k": EVAL_K
    }
    results["summary"] = summary

    # Persist results
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    with OUT_JSON.open("w", encoding="utf-8") as fh:
        json.dump(results, fh, ensure_ascii=False, indent=2)

    # Plot
    OUT_PLOT = PLOTS_DIR / "retrieval_plot.png"
    labels = ["baseline", "cross-encoder-rerank"]
    baseline_val = summary["precision_baseline_at_k_mean"] or 0.0
    rerank_val = summary["precision_rerank_at_k_mean"] or 0.0
    plt.figure(figsize=(6, 4))
    plt.bar(labels, [baseline_val, rerank_val], color=["#4C72B0", "#DD8452"])
    plt.ylabel(f"Precision@{EVAL_K}")
    plt.title("Baseline vs Cross-Encoder Rerank")
    plt.ylim(0, 1.0)
    for i, v in enumerate([baseline_val, rerank_val]):
        plt.text(i, v + 0.02, f"{v:.3f}", ha="center")
    plt.tight_layout()
    plt.savefig(OUT_PLOT, dpi=160)
    plt.close()

    print("Experiment complete. Results saved to:", OUT_JSON)
    print("Summary:", summary)


if __name__ == "__main__":
    run_experiment()