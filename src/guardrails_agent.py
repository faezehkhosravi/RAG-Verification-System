from __future__ import annotations
import json
import os
import re
from typing import List, Tuple, Dict, Any

# ---------------- PII patterns ----------------
_RE_EMAIL = re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")
_RE_PHONE = re.compile(r"\b(?:\+?\d{1,3}[-.\s]?)?(?:\(?\d{2,4}\)?[-.\s]?)?\d{3,4}[-.\s]?\d{3,4}\b")
_RE_IBAN = re.compile(r"\b[A-Z]{2}[0-9]{2}[A-Z0-9]{1,30}\b")
_RE_SSN_US = re.compile(r"\b\d{3}-\d{2}-\d{4}\b")

# ------------- Prompt-injection patterns -------------
_PROMPT_INJECTION_PATTERNS = [
    re.compile(r"ignore (all )?previous instructions", re.IGNORECASE),
    re.compile(r"disregard (all )?previous messages", re.IGNORECASE),
    re.compile(r"system:.*", re.IGNORECASE),
    re.compile(r"assistant:.*", re.IGNORECASE),
    re.compile(r"<\s*system\s*>", re.IGNORECASE),
    re.compile(r"```(bash|sh|python|eval|js|javascript)", re.IGNORECASE),
    re.compile(r"\beval\(", re.IGNORECASE),
    re.compile(r"curl\s+http", re.IGNORECASE),
    re.compile(r"wget\s+http", re.IGNORECASE),
]

def _mask_span(text: str, start: int, end: int, mask="[REDACTED]") -> str:
    return text[:start] + mask + text[end:]

# ---------------- Agent ----------------
class GuardrailsAgent:
    def __init__(self):
        self.metrics_path = "/content/drive/MyDrive/results/metrics.json"
        os.makedirs(os.path.dirname(self.metrics_path) or ".", exist_ok=True)

    def redact_pii(self, text: str) -> Tuple[str, List[Dict[str, Any]]]:
        """Redact emails, phones, IBANs, SSNs"""
        pii_items: List[Dict[str, Any]] = []
        sanitized = text

        patterns = [
            ("email", _RE_EMAIL),
            ("phone", _RE_PHONE),
            ("iban", _RE_IBAN),
            ("ssn_us", _RE_SSN_US)
        ]

        matches: List[Tuple[int,int,str,str]] = []
        for typ, pat in patterns:
            for m in pat.finditer(text):
                matches.append((m.start(), m.end(), typ, m.group(0)))

        matches.sort(key=lambda x: x[0], reverse=True)
        for start, end, typ, val in matches:
            pii_items.append({"type": typ, "match": val, "start": start, "end": end})
            sanitized = _mask_span(sanitized, start, end)

        return sanitized, pii_items

    def detect_prompt_injection(self, text: str) -> List[str]:
        flags: List[str] = []
        for pat in _PROMPT_INJECTION_PATTERNS:
            for m in pat.finditer(text):
                snippet = m.group(0)
                flags.append(f"prompt_injection_detected: pattern={pat.pattern}, snippet={snippet[:200]}")
        if flags:
            flags.insert(0, "high_risk_prompt_injection")
        return flags

    def sanitize_text(self, text: str) -> Tuple[str, List[str], List[Dict[str, Any]]]:
        flags = self.detect_prompt_injection(text)
        sanitized, pii_items = self.redact_pii(text)
        return sanitized, flags, pii_items

    def save_metrics(self, flags: List[str], pii_items: List[Dict[str, Any]]) -> str:
        metrics = {"flags": flags, "pii_items": pii_items}
        with open(self.metrics_path, "w", encoding="utf-8") as f:
            json.dump(metrics, f, indent=2, ensure_ascii=False)
        return self.metrics_path

