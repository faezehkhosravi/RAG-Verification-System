def summarize_chunk(chunk_text, idx):
    prompt = (
        f"Summarize the following OECD AI policy document in 3 sections: "
        f"[Overview], [Key Policies], [Governance Implications]. "
        f"Use clear human-readable language. Include citations like [src: file.pdf, p.{idx+1}].\n\n"
        f"{chunk_text}"
    )
    return summarizer(prompt, max_length=250, min_length=100, do_sample=False)[0]['summary_text']

