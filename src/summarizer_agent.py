import json
import os
import re
import textwrap
from dataclasses import dataclass
from typing import List, Tuple, Optional, Dict, Any, Callable

# ---------------------------
# Citation & Summary dataclasses
# ---------------------------
@dataclass
class Citation:
    filename: str
    page: int
    def fmt(self) -> str:
        return f"[src: {os.path.basename(self.filename)}, p.{self.page}]"

@dataclass
class StructuredSummary:
    title: str
    executive_summary: str
    key_points: List[str]
    evidence: List[Dict[str, Any]]  # {"point": str, "citations": [Citation]}
    recommendations: List[str]
    def to_dict(self) -> Dict[str, Any]:
        return {
            "title": self.title,
            "executive_summary": self.executive_summary,
            "key_points": self.key_points,
            "evidence": [
                {"point": e["point"], "citations": [c.fmt() for c in e.get("citations", [])]}
                for e in self.evidence
            ],
            "recommendations": self.recommendations
        }

# ---------------------------
# SummarizerAgent
# ---------------------------
class SummarizerAgent:
    def __init__(self, llm_fn: Optional[Callable[[str], str]] = None):
        self.llm_fn = llm_fn

    def _extractive_summary(self, pages: List[Tuple[str, int, str]]) -> StructuredSummary:
        sentences = []
        keywords = ["policy","recommend","risk","benefit","evidence","study","regulat"]
        sent_split = re.compile(r"(?<=[.!?])\s+")
        for fname, pnum, text in pages:
            if not text.strip():
                continue
            for s in sent_split.split(text):
                s_clean = s.strip()
                if len(s_clean) < 30:
                    continue
                score = len(s_clean)
                for kw in keywords:
                    if re.search(kw, s_clean, re.IGNORECASE):
                        score += 50
                sentences.append((s_clean, Citation(fname,pnum), score))

        if not sentences:
            return StructuredSummary(
                title="No Content",
                executive_summary="No extractable text.",
                key_points=[],
                evidence=[],
                recommendations=[]
            )

        sentences.sort(key=lambda x: x[2], reverse=True)
        top_sents = sentences[:6]

        key_points = [textwrap.shorten(t[0], width=200, placeholder="...") for t in top_sents]
        evidence = [{"point": textwrap.shorten(t[0], width=400), "citations":[t[1]]} for t in top_sents]
        exec_sum = " ".join(key_points[:3])
        recs = ["Consider regulatory options; balance innovation and safety."]
        return StructuredSummary(
            title="Extractive Summary",
            executive_summary=exec_sum,
            key_points=key_points,
            evidence=evidence,
            recommendations=recs
        )

    def summarize_documents(self, pages: List[Tuple[str,int,str]]) -> StructuredSummary:
        if not pages:
            raise ValueError("No pages provided.")
        # try LLM if exists
        if self.llm_fn:
            try:
                prompt = self._build_prompt(pages)
                resp = self.llm_fn(prompt)
                data = json.loads(resp)
                evidence = []
                for e in data.get("evidence", []):
                    citations = []
                    for c in e.get("citations", []):
                        m = re.search(r"\[src:\s*([^,]+),\s*p\.?\s*(\d+)\]", c)
                        if m:
                            citations.append(Citation(m.group(1), int(m.group(2))))
                    evidence.append({"point": e.get("point",""), "citations": citations})
                return StructuredSummary(
                    title=data.get("title",""),
                    executive_summary=data.get("executive_summary",""),
                    key_points=data.get("key_points",[]),
                    evidence=evidence,
                    recommendations=data.get("recommendations",[])
                )
            except Exception as e:
                print(f"LLM summarization failed: {e}")

        # fallback extractive
        return self._extractive_summary(pages)

    def _build_prompt(self, pages: List[Tuple[str,int,str]]) -> str:
        header = ("You are a policy summarizer. Produce structured summaries "
                  "with citations like [src: filename.pdf, p.X]. Return JSON with "
                  "fields: title, executive_summary, key_points, evidence, recommendations.")
        excerpts = []
        for fname, pnum, text in pages[:12]:
            excerpts.append(f"---\nFILE: {fname} | PAGE: {pnum}\n{text[:800]}")
        return header + "\n\n" + "\n".join(excerpts) + "\n\nReturn only valid JSON."

    def save_summary(self, summary: StructuredSummary, path: str):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path,"w",encoding="utf-8") as f:
            json.dump(summary.to_dict(), f, ensure_ascii=False, indent=2)
        print(f"Saved summary to {path}")

